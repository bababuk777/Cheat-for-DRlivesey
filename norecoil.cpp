#include "config.h"
#include <iostream>
#include <Windows.h>
#include "memory_functions.h"
#include "globals.h"

uintptr_t noRecoilVAddress = 0;
uintptr_t noRecoilHAddress = 0;

void FindNoRecoilAddress() {
	std::cout << "searching for no recoil addresses..." << std::endl;
	BYTE noRecoilVAddressBytes[] = { 0x41, 0xFF, 0xD3, 0xF3, 0x0F, 0x5A, 0xC0, 0x48, 0x8B, 0x85, 0xD8, 0xFE, 0xFF, 0xFF, 0x48, 0x8B, 0xC8, 0xF2, 0x0F, 0x10, 0xD0, 0xF2, 0x0F, 0x5A, 0xD2, 0x48, 0x8B, 0xD5, 0x48, 0x83, 0xC2, 0xC0, 0x4C, 0x8B, 0x45, 0xB0, 0x4C, 0x89, 0x45, 0xC0, 0x4C, 0x63, 0x45, 0xB8, 0x44, 0x89, 0x45, 0xC8, 0x48, 0x8D, 0x12, 0x83, 0x38, 0x00, 0x49, 0xBB};
	BYTE noRecoilHAddressBytes[] = { 0x41, 0xFF, 0xD3, 0xF3, 0x0F, 0x5A, 0xC0, 0x48, 0x8B, 0x85, 0xE0, 0xFE, 0xFF, 0xFF, 0x48, 0x8B, 0xC8, 0xF2, 0x0F, 0x10, 0xD0, 0xF2, 0x0F, 0x5A, 0xD2, 0x48, 0x8B, 0xD5, 0x48, 0x83, 0xC2, 0xE0, 0x4C, 0x8B, 0x45, 0xD0, 0x4C, 0x89, 0x45, 0xE0};
	{
		int size;
		uintptr_t* addresses = AOB(noRecoilVAddressBytes, sizeof(noRecoilVAddressBytes), size);
		if (size > 0) {
			noRecoilVAddress = addresses[0] + 0x40;
			noRecoilHAddress = addresses[0] + 0xE8;
			std::cout << "found: " << std::hex << noRecoilVAddress << std::dec << std::endl;
		}
		else {
			std::cout << "not found" << std::endl;
		}
	}
}

void NoRecoil() {
	if (!noRecoilVAddress)
	{
		return;
	}

	if (config.noRecoil)
	{
		std::cout << "enabled" << std::endl;
		byte noRecoilVBytes[] = { 0x90, 0x90, 0x90 };
		WBM(noRecoilVAddress, noRecoilVBytes, 3);
		WBM(noRecoilHAddress, noRecoilVBytes, 3);
	}
	else
	{
		std::cout << "disabled" << std::endl;
		byte noRecoilVBytes[] = { 0x41, 0xFF, 0xD3 };
		WBM(noRecoilVAddress, noRecoilVBytes, 3);
		WBM(noRecoilHAddress, noRecoilVBytes, 3);
	}
}